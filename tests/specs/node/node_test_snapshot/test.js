// Regression coverage for `t.assert.snapshot(value[, options])` and
// `require("node:test").snapshot` (Node 26.5.1,
// lib/internal/test_runner/snapshot.js). The stored snapshot file is the
// committed `test.js.snapshot`, in Node's format.

import assert from "node:assert";
import { describe, snapshot, test } from "node:test";

test("matches the stored snapshots, counted per test", (t) => {
  t.assert.snapshot({ value1: 1, value2: 2 });
  t.assert.snapshot("a `template` with ${dollar} and \\ backslash");
});

describe("suite", () => {
  test("keys include the suite", (t) => {
    t.assert.snapshot([1, 2, 3]);
  });
});

test("a mismatch is an AssertionError", (t) => {
  assert.throws(
    () => t.assert.snapshot({ changed: true }),
    { name: "AssertionError" },
  );
});

test("a missing snapshot names the --test-update-snapshots flag", (t) => {
  assert.throws(() => t.assert.snapshot(1), {
    code: "ERR_INVALID_STATE",
    snapshot: "a missing snapshot names the --test-update-snapshots flag 1",
    message:
      /^Invalid state: Snapshot 'a missing snapshot names the --test-update-snapshots flag 1' not found in '.+test\.js\.snapshot\.' Missing snapshots can be generated by rerunning the command with the --test-update-snapshots flag\.$/,
  });
});

test("custom serializers", (t) => {
  t.assert.snapshot(5, {
    serializers: [(value) => value * 2, (value) => `doubled: ${value}`],
  });
  assert.throws(() => t.assert.snapshot(1, { serializers: "x" }), {
    code: "ERR_INVALID_ARG_TYPE",
  });
});

test("snapshot API validation", () => {
  assert.throws(() => snapshot.setDefaultSnapshotSerializers([1]), {
    code: "ERR_INVALID_ARG_TYPE",
  });
  assert.throws(() => snapshot.setResolveSnapshotPath(1), {
    code: "ERR_INVALID_ARG_TYPE",
  });
});
